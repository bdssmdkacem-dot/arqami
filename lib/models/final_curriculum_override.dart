UnitModel _unit(
  int n,
  String title,
  String age,
  String description,
  String learnTitle,
  String explanation,
  List<String> examples,
  List<ChoiceQuestion> quiz,
  [List<ChoiceQuestion>? assessment],
) {
  return UnitModel(
    id: 'unit_${n.toString().padLeft(2, '0')}',
    order: n,
    titleAr: title,
    ageRangeAr: age,
    descriptionAr: description,
    activities: [
      LessonActivityConfig(titleAr: learnTitle, explanationAr: explanation, examplesAr: examples),
      MultipleChoiceActivityConfig(quiz),
      AssessmentActivityConfig(titleAr: 'اختبار الوحدة $n', questions: assessment ?? quiz),
    ],
  );
}

ChoiceQuestion _q(String question, List<String> options, int correct) => ChoiceQuestion(
      questionAr: question,
      options: options,
      correctIndex: correct,
    );
