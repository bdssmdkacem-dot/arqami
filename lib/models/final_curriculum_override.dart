UnitModel _unit(int n, String title, String age, String description, String learnTitle, String explanation, List<String> examples, List<ActivityConfig> extra, List<ChoiceQuestion> quiz, [List<ChoiceQuestion>? assessment]) {
  return UnitModel(
    id: 'unit_${n.toString().padLeft(2, '0')}',
    order: n,
    titleAr: title,
    ageRangeAr: age,
    descriptionAr: description,
    activities: [
      LessonActivityConfig(titleAr: learnTitle, explanationAr: explanation, examplesAr: examples),
      ...extra,
      MultipleChoiceActivityConfig(quiz),
      AssessmentActivityConfig(titleAr: 'اختبار الوحدة $n', questions: assessment ?? quiz),
    ],
  );
}

ChoiceQuestion _q(String question, List<String> options, int correct) => ChoiceQuestion(questionAr: question, options: options, correctIndex: correct);

MultipleChoiceActivityConfig _quiz(List<ChoiceQuestion> questions) => MultipleChoiceActivityConfig(questions);

ReviewActivityConfig _review(String title, List<ChoiceQuestion> questions) => ReviewActivityConfig(titleAr: title, questions: questions);

ArithmeticActivityConfig _arithmetic(String operation, List<ArithmeticQuestion> questions) => ArithmeticActivityConfig(operation: operation, questions: questions);

WordProblemActivityConfig _wordProblems(List<ArithmeticQuestion> questions) => WordProblemActivityConfig(questions);

ArithmeticQuestion _a(String question, num answer, [String? hint]) => ArithmeticQuestion(questionAr: question, correctAnswer: answer, hintAr: hint);

ArithmeticQuestion _at(String question, String answer, [String? hint]) => ArithmeticQuestion(questionAr: question, correctAnswerText: answer, hintAr: hint);
